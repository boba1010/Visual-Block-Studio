using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Text;

namespace XamlBlocksCompiler.SourceGeneration;

[Generator]
public sealed class XamlMetadataGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var controls = context.SyntaxProvider.ForAttributeWithMetadataName(
            "XamlBlocksCompiler.Syntax.XamlControlAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol);

        context.RegisterSourceOutput(controls, static (spc, type) =>
        {
            var excludedProperties = new HashSet<string>
            {
                "Namespaces",
                "Attributes",
                "Name",
                "Children"
            };

            var properties = GetProperties(type)
                 .Where(static property =>
                     property is
                     {
                         IsStatic: false,
                         IsIndexer: false,
                         DeclaredAccessibility: Accessibility.Public,
                         GetMethod: not null
                     })
                 .Where(static property => property.Name != "Content")
                 .Where(property => !excludedProperties.Contains(property.Name))
                 .ToArray();

            var source = GenerateMetadata(type, properties);

            spc.AddSource(
                $"{type.Name}.XamlMetadata.g.cs",
                SourceText.From(source, Encoding.UTF8));
        });
    }

    private static IEnumerable<IPropertySymbol> GetProperties(INamedTypeSymbol type)
    {
        var hierarchy = new Stack<INamedTypeSymbol>();

        for (var current = type; current is not null; current = current.BaseType)
        {
            hierarchy.Push(current);
        }

        while (hierarchy.Count > 0)
        {
            foreach (var property in hierarchy.Pop().GetMembers().OfType<IPropertySymbol>())
            {
                yield return property;
            }
        }
    }

    private static string GenerateValueExpression(IPropertySymbol property)
    {
        var typeName = property.Type.ToDisplayString();
        var value = $"control.{property.Name}";

        return typeName switch
        {
            "XamlBlocksCompiler.Models.Color" => $"{value}.ToHex()",
            "XamlBlocksCompiler.Models.Alignment" when property.Name == "VerticalAlignment" =>
                $$"""
                ({{value}}.ToString() switch
                {
                    "Center" => "Center",
                    "Start" => "Top",
                    "End" => "Bottom",
                    "Stretch" => "Stretch",
                    _ => throw new global::System.ArgumentOutOfRangeException()
                })
                """,

            "XamlBlocksCompiler.Models.Alignment" when property.Name == "HorizontalAlignment" =>
                $$"""
                ({{value}}.ToString() switch
                {
                    "Center" => "Center",
                    "Start" => "Left",
                    "End" => "Right",
                    "Stretch" => "Stretch",
                    _ => throw new global::System.ArgumentOutOfRangeException()
                })
                """,

            _ => $"global::System.Convert.ToString({value}, " + "global::System.Globalization.CultureInfo.InvariantCulture)"
        };
    }

    private static string GenerateMetadata(INamedTypeSymbol type, IPropertySymbol[] properties)
    {
        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();

        var propertyNames = string.Join(",\n        ", properties.Select(property => SymbolDisplay.FormatLiteral(property.Name, quote: true)));

        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        var attributeName = type.GetAttributes()
            .FirstOrDefault(attribute =>
                attribute.AttributeClass?.ToDisplayString() ==
                "XamlBlocksCompiler.Syntax.XamlControlAttribute")
            ?.ConstructorArguments.FirstOrDefault().Value as string
            ?? type.Name.Replace("Syntax", "");

        var namespaceDeclaration = ns is null ? "" : $"namespace {ns};";

        var source = $$"""
        // <auto-generated/>
        #nullable enable

        {{namespaceDeclaration}}

        public static class {{type.Name}}XamlMetadata
        {
            public const string ElementName = {{SymbolDisplay.FormatLiteral(attributeName, quote: true)}};

            public static readonly string[] PropertyNames =
            [
                {{propertyNames}}
            ];

            public static void WriteAttributes(global::System.Xml.XmlWriter writer, {{typeName}} control)
            {
                {{string.Join("\n        ", properties.Select(GenerateAttributeWriter))}}
            }
        }
        """;

        return source;
    }

    private static string GenerateAttributeWriter(IPropertySymbol property)
    {
        var propertyName = property.Name;
        var escapedName = SymbolDisplay.FormatLiteral(propertyName, quote: true);
        var valueExpression = GenerateValueExpression(property);

        if (property.Type.SpecialType is
            SpecialType.System_Double or
            SpecialType.System_Single or
            SpecialType.System_Int32 or
            SpecialType.System_Int64 or
            SpecialType.System_Int16 or
            SpecialType.System_Byte or
            SpecialType.System_Decimal)
        {
            return $$"""
        {
            var value = {{valueExpression}};
            if (value is not null &&
                global::System.Double.TryParse(
                    value,
                    global::System.Globalization.NumberStyles.Float,
                    global::System.Globalization.CultureInfo.InvariantCulture,
                    out var number) &&
                !global::System.Double.IsNaN(number))
            {
                writer.WriteAttributeString({{escapedName}}, value);
            }
        }
        """;
        }

        return $$"""
        writer.WriteAttributeString({{escapedName}}, {{valueExpression}});
        """;
    }
}